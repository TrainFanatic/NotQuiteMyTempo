"""Generate ANIMATIONS.md from the exported glbs (task B3 of OVERNIGHT.md).

Run with any Python 3 (no Blender needed):
    python3 gen_animations_md.py

Lengths come from the glb animation samplers; loop flags and key timings come from
terence/terence_v002_moves.json and the band constants below (mirroring band_anims.py).
"""

import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent
FPS = 24

BAND_LOOPS = {"rest", "play_loop", "arms_rest"}
BAND_TIMINGS = {
    "rest": "one slow breath and weight shift per loop, keys every 8 (phase varies per player)",
    "raise": "settles back and breathes in to 3, the instrument swings up on an arc from 2 and meets the "
             "mouth at 13, the torso leans in a little late and settles by 16 (playing pose at 16)",
    "play_loop": "4 beats at 120 BPM (12 frames per beat), keys every 2; trombone slide changes on each beat",
    "lower": "comes off the lips from 1, swings down on an arc, the torso slumps past rest around 13 and "
             "settles; rest pose at 16",
    "freeze": "braces in 3 with a small overshoot, settles by 6, held with a faint tremble to 24",
    "startle": "jolt peak at 4 (no anticipation), glance aside around 11, eased back to rest by 18",
    "look_down": "head leads and settles by 10, the body follows from 3 to 12, breathing hold to 36",
    "look_at_drummer": "turned to spot_drummer (aimed per seat): head leads by 10, torso twist follows "
                       "from 3 to 12, breathing hold to 36",
    "flip_page": "free hand travels round the instrument to the right page corner at 10, turns the page "
                 "on a forward arc by 20, back to rest by 30",
    "arms_rest": "both hands on the lap (the trumpet and guitar hand stays on the instrument), one slow "
                 "breath per loop",
    "spit_valve": "eases the trombone slide-down by 10, shakes the water out at 16 / 22 / 28, back to rest by 42",
}
BAND_ORDER = list(BAND_TIMINGS)
TIER_NAMES = {"t0": "Tier 0, rehearsal", "t1": "Tier 1, stops", "t2": "Tier 2, pressure", "t3": "Tier 3, close up",
              "t4": "Tier 4, rage", "t5": "Tier 5, violence", "ap": "Approval"}


def glb_json(path):
    d = path.read_bytes()
    n = struct.unpack("<I", d[12:16])[0]
    return json.loads(d[20:20 + n])


def anim_lengths(path):
    j = glb_json(path)
    acc = j["accessors"]
    out = {}
    for a in j.get("animations", []):
        out[a["name"]] = max(acc[s["input"]]["max"][0] for s in a["samplers"])
    return out


def fmt_timing(t):
    parts = []
    for k, v in t.items():
        if k in ("frames", "seconds", "loop"):
            continue
        if isinstance(v, list):
            v = ", ".join(str(x) for x in v)
        parts.append(f"{k.replace('_', ' ')} {v}")
    return "; ".join(parts) or "none"


def main():
    meta = json.loads((ROOT / "terence/terence_v002_moves.json").read_text())
    tl = anim_lengths(ROOT / "terence/terence_v002.glb")
    if set(tl) != set(meta["moves"]):
        raise RuntimeError(f"terence glb/json mismatch: {sorted(set(tl) ^ set(meta['moves']))}")
    lines = ["# Animations", "",
             "Generated by `gen_animations_md.py` from the exported glbs. Everything runs at 24 fps and 120 BPM "
             "(12 frames per beat). To follow a song, scale playback speed by `song_bpm / 120`. Frame numbers "
             "below are at 24 fps.", "",
             "## Conventions", "",
             "- **Characters** face -Y in Blender (+Z in glTF). Place them at their room marker with "
             "yaw = marker yaw + 180 degrees.",
             "- **Band instruments** ride the extra root bone `Instrument`; the trombone slide rides `InstrumentSlide`, "
             "which moves only along the instrument's local -Y. In Godot, attach the instrument glb under a "
             "`BoneAttachment3D` on that bone with a +90 degree rotation about X (not identity: imported joints keep "
             "Blender's bone axes). See `StateMachineBuilder.ATTACH_OFFSET` in the Godot project.",
             "- **Godot naming**: Godot's importer strips a `_loop` suffix (`play_loop` arrives as `play`). The Godot "
             "project's post-import script restores the name and sets loop modes from the table below.",
             "- **Terence's props** ride `PropR` / `PropL` the same way (same +90 degree X offset). At frame 0 the "
             "prop bone sits where the prop should already be.",
             f"- **Default targets** (Terence's local frame at spot_terence): the player's head at "
             f"{tuple(meta['targets']['DRUMMER_HEAD'])}. Close-up moves (t3_*, t5_rhythm_slaps, t5_cowbell) "
             f"expect Terence 0.70 m in front of the player, facing them, with the head at "
             f"{tuple(meta['targets']['NEAR_HEAD'])}.",
             "- **Faces**: Terence's face is a photo texture with no shape keys, so there is no facial animation.",
             "", "## Terence (`terence/terence_v002.glb`)", ""]
    current = None
    for name, m in meta["moves"].items():
        tier = name.split("_")[0]
        if tier != current:
            current = tier
            lines += ["", f"### {TIER_NAMES[tier]}", "", "| Action | Frames | Seconds | Loops | Key timings (frames) |",
                      "|---|---|---|---|---|"]
        secs = tl[name]
        lines.append(f"| `{name}` | {round(secs * FPS)} | {secs:.2f} | {'yes' if m['loop'] else 'no'} | {fmt_timing(m)} |")

    lines += ["", "## Band (`band/<member>.glb`)", "",
              "Every member has the same action names. Trombones add `spit_valve`. Lengths are identical across members.", "",
              "| Action | Frames | Seconds | Loops | Key timings (frames) |", "|---|---|---|---|---|"]
    bl = anim_lengths(ROOT / "band/band_trombone_1.glb")
    for name in BAND_ORDER:
        secs = bl[name]
        lines.append(f"| `{name}` | {round(secs * FPS)} | {secs:.2f} | {'yes' if name in BAND_LOOPS else 'no'} | {BAND_TIMINGS[name]} |")
    counts = {}
    for f in sorted((ROOT / "band").glob("band_*.glb")):
        counts[f.stem] = len(anim_lengths(f))
    lines += ["", "Actions per member: " + ", ".join(f"`{k}` {v}" for k, v in counts.items()) + ".", ""]
    (ROOT / "ANIMATIONS.md").write_text("\n".join(lines) + "\n")
    print(f"wrote ANIMATIONS.md: {len(meta['moves'])} Terence actions, {len(BAND_ORDER)} band actions")


if __name__ == "__main__":
    main()
